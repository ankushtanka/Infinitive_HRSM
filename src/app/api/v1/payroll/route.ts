export async function GET(req: NextRequest) {
  try {
    const auth = await getAuthContext(req);
    const perm = checkPermissions(auth);
    if (!perm.isAllowed) {
      return NextResponse.json({ success: false, message: perm.message }, { status: perm.statusCode });
    }

    const { db } = await connectToDatabase();
    const orgId = auth.organizationId;
    const recordQuery: any = { organizationId: orgId };
    if (auth.role === 'EMPLOYEE') {
      recordQuery.employeeId = auth.employeeId || '__NO_EMPLOYEE_PROFILE__';
    } else if (auth.role === 'MANAGER') {
      const managerId = auth.employeeId || '';
      const team = managerId
        ? await db.collection('employees').find({
            organizationId: orgId,
            $or: [{ managerId }, { reportingTo: managerId }, { employeeId: managerId }],
          }).project({ employeeId: 1, id: 1 }).limit(1001).toArray()
        : [];
      if (team.length > 1000) {
        return NextResponse.json({ success: false, message: 'Manager team is too large to load in one payroll view.' }, { status: 413 });
      }
      recordQuery.employeeId = {
        $in: team.map((employee) => employee.employeeId || employee.id || employee._id.toString()),
      };
    }

    const { searchParams } = new URL(req.url);
    const page = Math.max(1, Number.parseInt(searchParams.get('page') || '1', 10) || 1);
    const limit = Math.min(100, Math.max(1, Number.parseInt(searchParams.get('limit') || '50', 10) || 50));
    const privileged = PRIVILEGED_PAYROLL_ROLES.includes(auth.role);
    const [payrollRecords, totalCount, metricRows, salaryStructures, salaryRules, salaryAssignments, settingsDoc] = await Promise.all([
      db.collection('payroll_records').find(recordQuery).sort({ payYear: -1, payMonth: -1 }).skip((page - 1) * limit).limit(limit).toArray(),
      db.collection('payroll_records').countDocuments(recordQuery),
      db.collection('payroll_records').aggregate([
        { $match: recordQuery },
        { $group: {
          _id: null,
          totalNetDisbursed: { $sum: { $ifNull: ['$netSalary', 0] } },
          totalStatutoryDeductions: { $sum: { $add: [
            { $ifNull: ['$pf', 0] }, { $ifNull: ['$pt', 0] }, { $ifNull: ['$tds', 0] }, { $ifNull: ['$esi', 0] },
          ] } },
          payslipsCount: { $sum: { $cond: [{ $in: ['$status', ['APPROVED', 'PAID']] }, 1, 0] } },
          totalRecords: { $sum: 1 },
        } },
      ]).toArray(),
      privileged ? db.collection('salary_structures').find({ organizationId: orgId }).limit(500).toArray() : Promise.resolve([]),
      privileged ? db.collection('salary_rules').find({ organizationId: orgId }).limit(500).toArray() : Promise.resolve([]),
      privileged ? db.collection('salary_assignments').find({ organizationId: orgId }).limit(1000).toArray() : Promise.resolve([]),
      privileged ? db.collection('organization_settings').findOne({ organizationId: orgId }, { projection: { payroll: 1 } }) : Promise.resolve(null),
    ]);
    const metrics = metricRows[0] || { totalNetDisbursed: 0, totalStatutoryDeductions: 0, payslipsCount: 0 };

    return NextResponse.json({
      success: true,
      data: {
        payrollRecords,
        salaryStructures: salaryStructures.length > 0 ? salaryStructures : DEFAULT_SALARY_STRUCTURES,
        salaryRules: salaryRules.length > 0 ? salaryRules : DEFAULT_SALARY_RULES,
        salaryAssignments,
        payrollSettings: settingsDoc?.payroll || DEFAULT_PAYROLL_SETTINGS,
        metrics: {
          totalNetDisbursed: metrics.totalNetDisbursed,
          totalStatutoryDeductions: metrics.totalStatutoryDeductions,
          payslipsCount: metrics.payslipsCount,
          totalRecords: totalCount,
        },
        pagination: { page, limit, totalCount, totalPages: Math.ceil(totalCount / limit) },
      },
    });
  } catch (error) {
    console.error('Failed to fetch payroll records:', error);
    return NextResponse.json({ success: false, message: 'Failed to fetch payroll records.' }, { status: 500 });
  }
}

// POST /api/v1/payroll - calculate payroll from configured salary, leave, and attendance data.
export async function POST(req: NextRequest) {
  try {
    const auth = await getAuthContext(req);
    const perm = checkPermissions(auth, PRIVILEGED_PAYROLL_ROLES as any);
    if (!perm.isAllowed) {
      return NextResponse.json({ success: false, message: perm.message }, { status: perm.statusCode });
    }

    const body = await req.json();
    const payMonth = Number(body.month);
    const payYear = Number(body.year);
    if (!Number.isInteger(payMonth) || payMonth < 1 || payMonth > 12 || !Number.isInteger(payYear) || payYear < 2000 || payYear > 2200) {
      return NextResponse.json({ success: false, message: 'Pay month and year must be valid.' }, { status: 400 });
    }
    if (body.employeeIds !== undefined && (!Array.isArray(body.employeeIds) || body.employeeIds.some((id: unknown) => typeof id !== 'string' || !id.trim()) || body.employeeIds.length > 1000)) {
      return NextResponse.json({ success: false, message: 'Employee selection is invalid or exceeds the processing limit.' }, { status: 400 });
    }

    const monthNames = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];
    const monthName = monthNames[payMonth - 1];
    const payrollPeriod = String(payYear) + '-' + String(payMonth).padStart(2, '0');
    const payPeriod = monthName + ' ' + String(payYear);
    const monthStart = new Date(Date.UTC(payYear, payMonth - 1, 1));
    const monthEnd = new Date(Date.UTC(payYear, payMonth, 1));
    const monthStartKey = monthStart.toISOString().slice(0, 10);
    const monthEndKey = monthEnd.toISOString().slice(0, 10);
    const monthStartDay = monthStart.getTime();
    const monthEndDay = monthEnd.getTime() - 24 * 60 * 60 * 1000;

    const { db } = await connectToDatabase();
    const orgId = auth.organizationId;
    const employeeQuery: any = { organizationId: orgId, status: { $nin: ['Terminated', 'Former Employee', 'Inactive'] } };
    if (Array.isArray(body.employeeIds) && body.employeeIds.length > 0) {
      employeeQuery.employeeId = { $in: body.employeeIds };
    }
    const employees = await db.collection('employees').find(employeeQuery).limit(5001).toArray();
    if (employees.length > 5000) {
      return NextResponse.json({ success: false, message: 'Select at most 1,000 employees or split the payroll run into smaller batches.' }, { status: 413 });
    }
    if (employees.length === 0) {
      return NextResponse.json({ success: false, message: 'No eligible active employees were found.' }, { status: 400 });
    }

    const organizationSettings = await db.collection('organization_settings').findOne(
      { organizationId: orgId },
      { projection: { payroll: 1 } }
    );
    const payrollSettings = organizationSettings?.payroll || DEFAULT_PAYROLL_SETTINGS;

    const actualDays = (monthEnd.getTime() - monthStart.getTime()) / (24 * 60 * 60 * 1000);
    const workingDays = (!payrollSettings.workingDaysPerMonth || payrollSettings.workingDaysPerMonth === 'ACTUAL')
      ? actualDays
      : Number(payrollSettings.workingDaysPerMonth) || 26;
    const overtimeMultiplier = Number(payrollSettings.overtimeRateMultiplier) || 1.5;
    if (!Number.isFinite(workingDays) || workingDays <= 0 || workingDays > actualDays || !Number.isFinite(overtimeMultiplier) || overtimeMultiplier < 0) {
      return NextResponse.json({ success: false, message: 'Payroll working days and overtime multiplier must be configured with valid values.' }, { status: 422 });
    }

    const employeeIds = Array.from(new Set(employees.flatMap((employee) => [
      employee.employeeId,
      employee.id,
      employee._id?.toString(),
    ].filter((id): id is string => typeof id === 'string' && id.length > 0))));
    const [activeRules, assignments, structures, leaves, attendanceRecords, existingRecords, leaveTypes] = await Promise.all([
      db.collection('salary_rules').find({ organizationId: orgId, enabled: true }).limit(500).toArray(),
      db.collection('salary_assignments').find({ organizationId: orgId, employeeId: { $in: employeeIds } }).limit(10000).toArray(),
      db.collection('salary_structures').find({ organizationId: orgId }).limit(500).toArray(),
      db.collection('leaves').find({
        organizationId: orgId,
        employeeId: { $in: employeeIds },
        status: { $in: ['Approved', 'APPROVED', 'approved'] },
        $or: [
          { startDate: { $lt: monthEnd }, endDate: { $gte: monthStart } },
          { startDate: { $lt: monthEndKey }, endDate: { $gte: monthStartKey } },
        ],
      }).limit(50001).toArray(),
      db.collection('attendance').find({
        organizationId: orgId,
        employeeId: { $in: employeeIds },
        $or: [
          { date: { $gte: monthStart, $lt: monthEnd } },
          { date: { $gte: monthStartKey, $lt: monthEndKey } },
        ],
      }).limit(50001).toArray(),
      db.collection('payroll_records').find({
        organizationId: orgId,
        employeeId: { $in: employeeIds },
        payrollPeriod,
      }).toArray(),
      db.collection('leave_types').find({ organizationId: orgId }).limit(500).toArray(),
    ]);
    if (leaves.length > 50000 || attendanceRecords.length > 50000) {
      return NextResponse.json({ success: false, message: 'This payroll period contains too many attendance or leave records for a safe batch. Split the employee selection and retry.' }, { status: 413 });
    }

    const findRule = (code: string, namePart: string) => activeRules.find((rule) =>
      rule.code === code || String(rule.name || '').toLowerCase().includes(namePart)
    );
    const pfRule = findRule('DED_PF', 'provident fund');
    const ptRule = findRule('DED_PT', 'professional tax');
    const tdsRule = findRule('DED_TDS', 'tax');
    const esiRule = findRule('DED_ESI', 'esi');
    const configuredValue = (rule: any, fallback: unknown) => rule ? Number(rule.value) : Number(fallback);
    const pfPercent = configuredValue(pfRule, payrollSettings.pfContributionPercent);
    const esiPercent = configuredValue(esiRule, payrollSettings.esiContributionPercent);
    const ptAmount = ptRule ? Number(ptRule.value) : 0;
    const tdsPercent = tdsRule ? Number(tdsRule.value) : 0;
    if (![pfPercent, esiPercent, ptAmount, tdsPercent].every((value) => Number.isFinite(value) && value >= 0)) {
      return NextResponse.json({ success: false, message: 'Configured statutory payroll rules contain invalid values.' }, { status: 422 });
    }

    // HR can switch PF / ESI off for this payroll run.
// Missing or true = deduct as before; only an explicit false skips it.
    const deductPf = body.deductPf !== false;
    const deductEsi = body.deductEsi !== false;

    const dateKey = (value: any): string | null => {
      if (value === undefined || value === null || value === '') return null;
      const parsed = value instanceof Date ? value : new Date(value);
      return Number.isNaN(parsed.getTime()) ? null : parsed.toISOString().slice(0, 10);
    };
    const daysWithinPeriod = (start: any, end: any): string[] => {
      const startKey = dateKey(start);
      const endKey = dateKey(end);
      if (!startKey || !endKey || endKey < monthStartKey || startKey >= monthEndKey || endKey < startKey) return [];
      const from = Math.max(Date.parse(startKey + 'T00:00:00.000Z'), monthStartDay);
      const to = Math.min(Date.parse(endKey + 'T00:00:00.000Z'), monthEndDay);
      const result: string[] = [];
      for (let day = from; day <= to; day += 24 * 60 * 60 * 1000) result.push(new Date(day).toISOString().slice(0, 10));
      return result;
    };

    const attendanceByEmployee = new Map<string, Map<string, { absent: boolean; overtimeHours: number }>>();
    for (const record of attendanceRecords) {
      const empId = String(record.employeeId || '');
      const key = dateKey(record.date);
      if (!empId || !key) continue;
      const dayMap = attendanceByEmployee.get(empId) || new Map<string, { absent: boolean; overtimeHours: number }>();
      const prior = dayMap.get(key);
      const status = String(record.status || '').toLowerCase();
      const overtime = Number(record.overtimeHours || 0);
      dayMap.set(key, {
        absent: Boolean(prior?.absent || status === 'absent'),
        overtimeHours: Math.max(prior?.overtimeHours || 0, Number.isFinite(overtime) && overtime > 0 ? overtime : 0),
      });
      attendanceByEmployee.set(empId, dayMap);
    }

    const existingByEmployee = new Map(existingRecords.map((record) => [String(record.employeeId), record]));
    const bulkOperations: any[] = [];
    const processedRecordsSummary: any[] = [];
    const missingSalaryIds: string[] = [];
    let skippedProtectedCount = 0;
    const now = new Date();

    const unpaidTypeSet = new Set<string>();
    for (const lt of leaveTypes) {
      if (lt.isPaid === false || lt.isPaid === 'false') {
        if (lt.name) unpaidTypeSet.add(lt.name.toLowerCase().trim());
        if (lt.code) unpaidTypeSet.add(lt.code.toLowerCase().trim());
      }
    }

    for (const employee of employees) {
      const empId = String(employee.employeeId || employee.id || employee._id.toString());
      const mongoId = employee._id.toString();
      const allEmpKeys = Array.from(new Set([
        empId,
        mongoId,
        String(employee.employeeId || ''),
        String(employee.id || ''),
        String(employee._id || ''),
      ].filter(Boolean)));

      const employeeAssignments = assignments.filter((assignment) =>
        allEmpKeys.includes(String(assignment.employeeId || ''))
      );
      let validAssignment = employeeAssignments
        .filter((assignment) => assignment.status !== 'Superceded' && assignment.status !== 'SUPERSEDED')
        .find((assignment) => {
          const from = dateKey(assignment.effectiveFrom);
          const to = dateKey(assignment.effectiveTo);
          return (!from || from < monthEndKey) && (!to || to >= monthStartKey);
        });

      // Auto-assign standard ₹25,000 structure if requested or allowed as fallback
      if (!validAssignment && (body.autoAssignStandard === true || body.allowStandardFallback === true)) {
        const fromDate = new Date(Date.UTC(payYear, 0, 1));
        const autoDoc = {
          _id: new ObjectId(),
          organizationId: orgId,
          employeeId: empId,
          salaryStructureId: 'struct-std',
          basicSalary: 12500,
          hra: 3750,
          conveyance: 2353,
          medical: 0,
          specialAllowance: 6397,
          otherAllowances: 0,
          bonus: 0,
          effectiveFrom: fromDate,
          effectiveTo: null,
          status: 'Active',
          assignedBy: auth.email || auth.userId,
          createdAt: now,
          updatedAt: now,
        };
        await db.collection('salary_assignments').insertOne(autoDoc);
        validAssignment = autoDoc;
      }

      if (!validAssignment) {
        missingSalaryIds.push(empId);
        continue;
      }

      const structure = structures.find((item) =>
        item.id === validAssignment.salaryStructureId || item._id?.toString() === validAssignment.salaryStructureId
      );
      const basic = Number(validAssignment.basicSalary ?? structure?.basicSalary);
      if (!Number.isFinite(basic) || basic < 0) {
        missingSalaryIds.push(empId);
        continue;
      }
      const component = (assignmentValue: unknown, structureValue: unknown, fallback = 0) => {
        const value = assignmentValue ?? structureValue ?? fallback;
        const parsed = Number(value);
        return Number.isFinite(parsed) && parsed >= 0 ? parsed : NaN;
      };
      const hraValue = validAssignment.hra ?? structure?.hra ?? structure?.hraValue;
      let hra = validAssignment.hra !== undefined
        ? component(validAssignment.hra, undefined)
        : structure?.hraType === 'PercentBasic' && hraValue !== undefined
          ? Math.round(basic * Number(hraValue) / 100)
          : component(undefined, hraValue);
      let conveyance = component(validAssignment.conveyance, structure?.conveyance);
      const medical = component(validAssignment.medical, structure?.medical);
      let specialAllowance = component(validAssignment.specialAllowance, structure?.specialAllowance);
      const otherAllowances = component(validAssignment.otherAllowances, structure?.otherAllowances);
      const bonus = component(validAssignment.bonus, structure?.bonus);

      // Enterprise default breakdown alignment for ₹25,000 standard gross (Basic: ₹12,500)
      if (basic === 12500) {
        if (!validAssignment.conveyance && conveyance === 0) conveyance = 2353;
        if (!validAssignment.specialAllowance && specialAllowance === 0) specialAllowance = 6397;
        if (!validAssignment.hra && (hra === 0 || hra === 5000)) hra = 3750; // 30% of Basic
      }

      if (![hra, conveyance, medical, specialAllowance, otherAllowances, bonus].every(Number.isFinite)) {
        missingSalaryIds.push(empId);
        continue;
      }

      const employeeKeys = new Set([empId, mongoId, String(employee.id || '')]);
      const approvedLeaveDayMap = new Map<string, number>();
      const unpaidLeaveDayMap = new Map<string, number>();

      const processedLeaveIds = new Set<string>();
      for (const leave of leaves) {
        if (!employeeKeys.has(String(leave.employeeId || ''))) continue;
        const leaveKey = leave._id?.toString() || leave.id || `${leave.startDate}_${leave.session || ''}`;
        if (processedLeaveIds.has(leaveKey)) continue;
        processedLeaveIds.add(leaveKey);

        const days = daysWithinPeriod(leave.startDate, leave.endDate);
        const dayFraction = leave.durationType === 'HALF_DAY' ? 0.5 : (leave.durationDays && Number(leave.durationDays) < 1 ? Number(leave.durationDays) : 1);
        const ltLower = String(leave.leaveType || '').toLowerCase().trim();
        const isUnpaid = unpaidTypeSet.has(ltLower) || ltLower.includes('unpaid') || ltLower.includes('lop') || ltLower.includes('without pay');

        for (const day of days) {
          const currentLeaveVal = approvedLeaveDayMap.get(day) || 0;
          approvedLeaveDayMap.set(day, Math.min(1, currentLeaveVal + dayFraction));

          if (isUnpaid) {
            const currentUnpaidVal = unpaidLeaveDayMap.get(day) || 0;
            unpaidLeaveDayMap.set(day, Math.min(1, currentUnpaidVal + dayFraction));
          }
        }
      }

      const employeeAttendance = new Map<string, { absent: boolean; overtimeHours: number }>();
      for (const key of employeeKeys) {
        const dayMap = attendanceByEmployee.get(key);
        if (dayMap) {
          for (const [day, value] of dayMap) {
            const previous = employeeAttendance.get(day);
            employeeAttendance.set(day, {
              absent: Boolean(previous?.absent || value.absent),
              overtimeHours: (previous?.overtimeHours || 0) + value.overtimeHours,
            });
          }
        }
      }
      const absentDays = new Set(Array.from(employeeAttendance.entries()).filter(([, value]) => value.absent).map(([day]) => day));

      const totalLeaveFraction = Array.from(approvedLeaveDayMap.values()).reduce((sum, f) => sum + f, 0);
      const totalUnpaidFraction = Array.from(unpaidLeaveDayMap.values()).reduce((sum, f) => sum + f, 0);

      // Absent days that don't already have an approved unpaid leave record
      let additionalAbsentCount = 0;
      for (const absentDay of absentDays) {
        const unpaidCovered = unpaidLeaveDayMap.get(absentDay) || 0;
        additionalAbsentCount += Math.max(0, 1 - unpaidCovered);
      }

      const leaveDays = Math.min(workingDays, Math.round(totalLeaveFraction * 10) / 10);
      const lopDays = Math.min(workingDays, Math.round((totalUnpaidFraction + additionalAbsentCount) * 10) / 10);
      const paidDays = Math.max(0, Math.round((workingDays - lopDays) * 10) / 10);
      const overtimeHours = Array.from(employeeAttendance.values()).reduce((total, day) => total + day.overtimeHours, 0);
      const configuredHourlyRate = validAssignment.overtimeRatePerHour;
      const overtimeRate = configuredHourlyRate === undefined
        ? (basic / workingDays / 8) * overtimeMultiplier
        : Number(configuredHourlyRate);
      if (!Number.isFinite(overtimeRate) || overtimeRate < 0) {
        return NextResponse.json({ success: false, message: 'A salary assignment contains an invalid overtime rate.' }, { status: 422 });
      }
      const overtimePay = Math.round(overtimeHours * overtimeRate);
      const grossSalary = basic + hra + conveyance + medical + specialAllowance + otherAllowances + overtimePay + bonus;
      const lopDeduction = lopDays > 0 ? Math.round((basic / workingDays) * lopDays) : 0;
      const pf = deductPf && pfPercent > 0 ? Math.round(basic * (pfPercent / 100)) : 0;
      const pt = ptAmount;
      const taxEnabled = payrollSettings.taxDeductionEnabled !== false;
      const tds = taxEnabled && tdsPercent > 0 ? Math.round(grossSalary * (tdsPercent / 100)) : 0;
      const esi = deductEsi && esiPercent > 0 ? Math.round(grossSalary * (esiPercent / 100)) : 0;      
      const otherDeductions = 0;
      const totalDeductions = lopDeduction + pf + pt + tds + esi + otherDeductions;
      const netSalary = Math.max(0, grossSalary - totalDeductions);

      const previousRecord = existingByEmployee.get(empId);
      if (previousRecord && ['APPROVED', 'PAID'].includes(String(previousRecord.status || '').toUpperCase())) {
        skippedProtectedCount++;
        continue;
      }

      const recordDoc = {
        organizationId: orgId,
        employeeId: empId,
        employeeName: employee.fullName || (String(employee.firstName || '') + ' ' + String(employee.lastName || '')).trim(),
        avatar: employee.avatar || '',
        department: employee.department || 'General',
        designation: employee.designation || 'Staff',
        joiningDate: employee.joiningDate || '',
        payPeriod,
        payMonth,
        payYear,
        payrollPeriod,
        workingDays,
        paidDays,
        leaveDays,
        lopDays,
        overtimeHours,
        overtimePay,
        bonus,
        basic,
        allowances: { hra, conveyance, medical, specialAllowance, otherAllowances },
        grossSalary,
        pf,
        pt,
        tds,
        esi,
        pfDeduction: pf,
        ptDeduction: pt,
        taxDeduction: tds,
        esiDeduction: esi,
        otherDeductions,
        totalDeductions,
        netSalary,
        status: 'PROCESSED',
        processedBy: auth.email || auth.userId,
        processedAt: now,
        updatedAt: now,
      };
      processedRecordsSummary.push(recordDoc);
      bulkOperations.push({
        updateOne: {
          filter: { organizationId: orgId, employeeId: empId, payrollPeriod, status: { $nin: ['APPROVED', 'PAID'] } },
          update: { $set: recordDoc, $setOnInsert: { createdAt: now } },
          upsert: true,
        },
      });
    }

    if (missingSalaryIds.length > 0) {
      return NextResponse.json({
        success: false,
        code: 'SALARY_ASSIGNMENT_REQUIRED',
        message: 'Payroll was not processed because one or more employees lack a valid effective salary assignment.',
        blockedEmployees: Array.from(new Set(missingSalaryIds)),
        employeesMissingSalary: Array.from(new Set(missingSalaryIds)),
      }, { status: 422 });
    }

    if (bulkOperations.length > 0) {
      await db.collection('payroll_records').bulkWrite(bulkOperations, { ordered: true });
    }

    await logAuditEvent(req, 'PROCESS_PAYROLL', {
      details: { payPeriod, count: bulkOperations.length, skippedProtectedCount, month: payMonth, year: payYear },
    });

    return NextResponse.json({
      success: true,
      message: 'Processed ' + bulkOperations.length + ' employee(s) for ' + payPeriod + '; protected approved/paid records skipped: ' + skippedProtectedCount + '.',
      count: bulkOperations.length,
      skippedProtectedCount,
      data: processedRecordsSummary,
    });
  } catch (error) {
    console.error('Payroll processing failed:', error);
    return NextResponse.json({ success: false, message: 'Payroll processing failed.' }, { status: 500 });
  }
}
